/**
 * Extract the version string from a Bitcoin user agent.
 * e.g. "/Satoshi:27.0.0/" -> "27.0"
 *      "/Satoshi:0.21.1/" -> "0.21.1"
 */
export function parseUserAgentVersion(userAgent: string): string | undefined {
  const match = userAgent.match(/\/Satoshi:(\d+\.\d+(?:\.\d+)?(?:\.\d+)?)\//);
  return match?.[1];
}

/**
 * Look up the release date for a given user agent string.
 * Returns the ISO date string or undefined if not found.
 */
export function getReleaseDate(userAgent: string): string | undefined {
  const version = parseUserAgentVersion(userAgent);
  if (!version) return undefined;

  // Try exact match first
  const exact = BITCOIN_CORE_RELEASES.get(version);
  if (exact) return exact;

  // Try stripping trailing ".0" (e.g. "27.0.0" -> "27.0")
  const stripped = version.replace(/\.0$/, "");
  return BITCOIN_CORE_RELEASES.get(stripped);
}
